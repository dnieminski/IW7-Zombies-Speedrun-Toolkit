const fs = require('fs');
const path = require('path');
const profiles = require('./map-profiles.cjs');
const root = path.resolve(__dirname, '..');
const quote = JSON.stringify;
const array = xs => '[' + xs.map(x => typeof x === 'number' ? x : quote(x)).join(', ') + ']';
let gsc = '// BEGIN GENERATED MAP PROFILES\nconfigure_map()\n{\n    switch (level.br_map)\n    {\n';
let lua = '-- Generated by tools/generate-profiles.cjs. Edit tools/map-profiles.cjs.\nreturn {\n    order = ' + '{' + profiles.map(p => quote(p.id)).join(', ') + '},\n';
for (const p of profiles) {
  const ids = p.splits.map(s => s.id);
  if (new Set(ids).size !== ids.length || ids.some(id => id < 0 || id > 14)) throw Error('Invalid split IDs: ' + p.id);
  if (p.splits.length > 15 || p.splits.filter(s => s.kind === 'finish').length !== 1) throw Error('Invalid profile: ' + p.id);
  for (const key of p.required) if (!p.splits.some(s => s.name === key)) throw Error('Missing requirement ' + key);
  const names = Array(15).fill(''), events = Array(15).fill(''), kinds = Array(15).fill(''), stages = Array(15).fill(-1);
  for (const s of p.splits) { names[s.id] = s.name; events[s.id] = s.event; kinds[s.id] = s.kind; stages[s.id] = s.stage; }
  gsc += '        case ' + quote(p.id) + ':\n';
  for (const [name, value] of Object.entries({names, events, kinds, stages, required:p.required})) gsc += '            level.br_' + name + ' = ' + array(value) + ';\n';
  gsc += '            level.br_finish_event = ' + quote(p.finish.event) + ';\n            level.br_finish_kind = ' + quote(p.finish.kind) + ';\n            level.br_finish_guard = ' + quote(p.finish.guard) + ';\n            level.br_finish_index = ' + p.finish.id + ';\n            return 1;\n';
  lua += '    [' + quote(p.id) + '] = {name = ' + quote(p.name) + ', short = ' + quote(p.short) + ', finishLabel = ' + quote(p.finishLabel) + ', splits = {\n';
  for (const s of p.splits) lua += '        {' + quote(s.name) + ', ' + quote(s.label) + ', ' + s.id + '},\n';
  lua += '    }},\n';
}
gsc += '    }\n    return 0;\n}\n// END GENERATED MAP PROFILES';
lua += '}\n';
const mainPath = path.join(root, 'iw7-mod/custom_scripts/cp/beast_runner.gsc');
const original = fs.readFileSync(mainPath, 'utf8');
const pattern = /\/\/ BEGIN GENERATED MAP PROFILES[\s\S]*?\/\/ END GENERATED MAP PROFILES/;
const updated = pattern.test(original) ? original.replace(pattern, gsc) : original.trimEnd() + '\n\n' + gsc + '\n';
const luaPath = path.join(root, 'iw7-mod/ui_scripts/BeastRunner/maps.lua');
if (process.argv.includes('--check')) {
  if (updated !== original || !fs.existsSync(luaPath) || fs.readFileSync(luaPath, 'utf8') !== lua) throw Error('Generated profiles are stale');
  console.log('PASS: five generated GSC/Lua profiles agree');
} else {
  fs.writeFileSync(mainPath, updated);
  fs.writeFileSync(luaPath, lua);
  console.log('Generated profiles for ' + profiles.length + ' maps');
}
